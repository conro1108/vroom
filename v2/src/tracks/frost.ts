// Frost Cup: "every lap is a choice". Forks are one wide road split by a median, and
// surface is per piece, not per lane, so a lane's risk comes from its shape: a tight
// inside line with a pad on it against a long safe sweep. Ice only sits straight
// after something slow: bots brake for the line's curve, not for the surface. A thin
// divider on the run-in commits bots to their lane early, or they swerve for it at
// the nose and grind down the median, and the median sits well off to the risky
// side so the brave lane is a gap you have to aim for.
import { L, R, S, type Feature, type TrackDef } from "../sim/course";
import type { Cup } from "./index";

/** Kickers wall to wall and pads 19m back; see `leap` in tide.ts for why. */
